 assert.ok(exported.notes.some(n=>n.scenario_id==='CK-R03'&&n.note===note&&n.recommendation==='revise'));
 checks.push('JSON export links notes to source digest without approval');
 assert.equal(await page.evaluate(()=>window.__reviewProbe),undefined);checks.push('annotation HTML is inert');
 await page.reload();await page.locator('[data-scene="CK-R03"]').click();assert.equal(await page.getByLabel('具体意见').inputValue(),note);checks.push('local notes reload');
