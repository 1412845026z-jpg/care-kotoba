 const result={checks,passed:checks.length,page_errors:errors,http_requests:network,counts,viewport_mobile:sizes,exported_source_digest:exported.source_digest,real_ai_calls:0,professional_reviewed:false};
 writeFileSync(join(out,'browser-results.json'),JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));
