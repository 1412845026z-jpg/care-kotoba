 await page.locator('[data-scene="CK-P01"]').click();await page.getByRole('tab',{name:'评测片段'}).click();
 assert.equal(await page.getByText('查看评分草稿 · 不作为模型输入',{exact:true}).count(),4);
 await page.getByText('查看评分草稿 · 不作为模型输入',{exact:true}).first().click();
 assert.ok(await page.getByText('来源与核实状态：符合此项',{exact:true}).count()>0);checks.push('paired feedback and readable draft labels');
