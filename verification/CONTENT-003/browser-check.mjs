 await page.getByRole('tab',{name:'对话规格'}).click();await page.getByRole('tab',{name:'对话规格'}).focus();await page.keyboard.press('ArrowRight');
 assert.equal(await page.getByRole('tab',{name:'相关术语'}).getAttribute('aria-selected'),'true');checks.push('keyboard tab navigation');
 await page.getByRole('tab',{name:'对话规格'}).click();await page.screenshot({path:join(out,'desktop.png'),fullPage:false});
