#!/usr/bin/env node
// Writes prototype/lib/notices-data.ts (the in-app 「ライセンスとデータの扱い」 page loads it on demand) from
// tools/notices/manifest.json and the license texts in docs/licenses/.
//   node tools/notices/generate.mjs           write
//   node tools/notices/generate.mjs --check   exit 1 if the committed file is out of date
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const manifest = JSON.parse(readFileSync(join(repo, 'tools', 'notices', 'manifest.json'), 'utf8'));
const out = join(repo, 'prototype', 'lib', 'notices-data.ts');
const problems = [];
const components = manifest.components.map((c) => {
  const path = join(repo, 'docs', 'licenses', c.file);
  if (!existsSync(path)) { problems.push(`${c.name}: missing docs/licenses/${c.file}`); return null; }
  for (const k of ['name', 'version', 'license', 'url', 'role_ja']) if (!c[k]) problems.push(`${c.name}: ${k} missing`);
  return { name: c.name, version: c.version, license: c.license, url: c.url, roleJa: c.role_ja, text: readFileSync(path, 'utf8').replace(/\r\n/g, '\n').trim() };
});
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
const body = `// GENERATED by tools/notices/generate.mjs from tools/notices/manifest.json and docs/licenses/ — do not edit.
export type Notice = { name: string; version: string; license: string; url: string; roleJa: string; text: string };
export const NOTICES: Notice[] = ${JSON.stringify(components, null, 1)};
`;
if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== body) { console.error(`${out} is out of date: run node tools/notices/generate.mjs`); process.exit(1); }
  console.log(`notices: ${components.length} components, up to date`);
} else {
  writeFileSync(out, body);
  console.log(`notices: ${components.length} components, wrote ${out}`);
}
