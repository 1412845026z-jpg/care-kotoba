#!/usr/bin/env node
// Generates prototype/lib/furigana-data.ts: furigana for the app's FIXED Japanese text
// (scene titles, contexts, opening lines, reference phrases, goals, variant labels, demo replies).
//
// Readings come from kuromoji.js (Apache-2.0) with its bundled mecab-ipadic-2.7.0 dictionary
// (NAIST/ICOT notice: docs/licenses/MECAB_IPADIC_NOTICE.txt). kuromoji is only a build-time tool;
// nothing from it is shipped except the generated readings.
// Machine readings are then corrected by hand in tools/furigana/overrides.json (keyed by the plain text).
//
// Usage (from the repository root):
//   node tools/furigana/generate.mjs --kuromoji <dir of a kuromoji.js checkout or package> [--check]
//   (the kuromoji dir needs its dependencies `async` and `doublearray` resolvable, e.g. via NODE_PATH)
//   --check: exit 1 if the committed data file differs from what would be generated.
import { readFileSync, writeFileSync, mkdtempSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const proto = join(repo, 'prototype');
const args = process.argv.slice(2);
const opt = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
const check = args.includes('--check');
const { toolRequire } = await import(pathToFileURL(join(proto, 'tests', 'harness', 'tool-require.mjs')).href);
const esbuild = toolRequire('esbuild');

// 1. Collect the fixed strings from lib/content.ts (bundled so the TypeScript source is the single source).
const tmp = mkdtempSync(join(tmpdir(), 'ck-furigana-'));
const entry = join(tmp, 'entry.mjs');
writeFileSync(entry, `import { scenes, variants, categories, demoReplies } from ${JSON.stringify(join(proto, 'lib', 'content.ts'))};
export const texts = [
  ...categories.map((c) => c.name),
  ...variants.flatMap((v) => [v.label, v.sub]),
  ...scenes.flatMap((s) => [s.title, s.context, s.starter, ...s.phrases, ...s.goals]),
  ...Object.values(demoReplies).flat(),
  'この理解で、合っていますか。',
];`);
await esbuild.build({ entryPoints: [entry], outfile: join(tmp, 'texts.mjs'), bundle: true, platform: 'node', format: 'esm', logLevel: 'error' });
const { texts } = await import(pathToFileURL(join(tmp, 'texts.mjs')).href);
const unique = [...new Set(texts.filter(Boolean))];

// 2. Tokenise with kuromoji.
const kuromojiDir = opt('--kuromoji') || process.env.CK_KUROMOJI_DIR;
if (!kuromojiDir || !existsSync(join(kuromojiDir, 'package.json'))) throw new Error('pass --kuromoji <dir> (a kuromoji.js checkout or installed package)');
const kpkg = JSON.parse(readFileSync(join(kuromojiDir, 'package.json'), 'utf8'));
const kuromoji = createRequire(join(kuromojiDir, 'package.json'))(join(kuromojiDir, kpkg.main || 'src/kuromoji.js'));
const tokenizer = await new Promise((ok, fail) => kuromoji.builder({ dicPath: join(kuromojiDir, 'dict') }).build((e, t) => (e ? fail(e) : ok(t))));

const KANJI = /[㐀-䶿一-鿿豈-﫿々〆]/;
const RUN = /[㐀-䶿一-鿿豈-﫿々〆]+|[^㐀-䶿一-鿿豈-﫿々〆]+/g;
const kata2hira = (s) => s.replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60));
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const unresolved = [];

export function annotateToken(surface, reading) {
  if (!KANJI.test(surface)) return surface;
  if (!reading || reading === '*') { unresolved.push(surface); return surface; }
  const r = kata2hira(reading);
  const runs = surface.match(RUN);
  const m = new RegExp('^' + runs.map((x) => (KANJI.test(x) ? '(.+?)' : esc(kata2hira(x)))).join('') + '$').exec(r);
  if (!m) return `{${surface}|${r}}`;
  let i = 1;
  return runs.map((x) => (KANJI.test(x) ? `{${x}|${m[i++]}}` : x)).join('');
}

const auto = {};
for (const t of unique) auto[t] = tokenizer.tokenize(t).map((tok) => annotateToken(tok.surface_form, tok.reading)).join('');

// 3. Apply reviewed corrections.
const overridesPath = join(repo, 'tools', 'furigana', 'overrides.json');
const overrides = existsSync(overridesPath) ? JSON.parse(readFileSync(overridesPath, 'utf8')) : {};
const plain = (n) => n.replace(/\{([^{}|]+)\|([^{}|]+)\}/g, '$1');
for (const [k, v] of Object.entries(overrides)) {
  if (k.startsWith('//')) continue;
  if (plain(v) !== k) throw new Error(`override does not annotate its key: ${k}`);
  if (!(k in auto)) console.warn(`override for text no longer in content: ${k}`);
}
const data = Object.fromEntries(unique.filter((t) => KANJI.test(t)).map((t) => [t, overrides[t] ?? auto[t]]));

const header = `// GENERATED by tools/furigana/generate.mjs — do not edit by hand; put corrections in tools/furigana/overrides.json.
// Readings: kuromoji.js ${kpkg.version} (Apache-2.0) + mecab-ipadic-2.7.0-20070801 (NAIST/ICOT; notice in
// docs/licenses/MECAB_IPADIC_NOTICE.txt), corrected by hand. Reviewed by Claude 2026-10-23;
// still needs review by a native-speaker Japanese teacher before release.
// Notation: {漢字|かんじ}. ${Object.keys(data).length} texts, ${Object.keys(overrides).filter((k) => !k.startsWith('//')).length} hand corrections.
`;
const out = header + 'export const FURIGANA: Record<string, string> = ' + JSON.stringify(data, null, 1).replace(/^ /gm, '  ') + ';\n';
const target = join(proto, 'lib', 'furigana-data.ts');
if (check) {
  const same = existsSync(target) && readFileSync(target, 'utf8') === out;
  console.log(same ? 'furigana data up to date' : 'furigana data is stale: run without --check');
  process.exit(same ? 0 : 1);
}
writeFileSync(target, out);
console.log(JSON.stringify({ texts: unique.length, annotated: Object.keys(data).length, overrides: Object.keys(overrides).length, unresolved: [...new Set(unresolved)] }, null, 1));
