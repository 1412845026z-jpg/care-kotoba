// Offline harness build: bundles the real app code with esbuild so it can be
// exercised in a browser without vinext/vite (see tests/harness/README.md).
//
//   client: app/page.tsx (the real learner app) rendered with react-dom/client
//   server: every app/api/**/route.ts (the real route handlers) for Node
//
// Differences from the production framework are deliberate and documented:
// no SSR/RSC, `lucide-react` replaced by placeholder icons when it is not
// installed, `cloudflare:workers` env mapped to process.env.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, existsSync, rmSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { toolRequire, moduleDirs, projectRoot } from './tool-require.mjs';

const esbuild = toolRequire('esbuild');
export const buildDir = join(projectRoot, 'tests', 'harness', '.build');

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

function hasPackage(name) {
  return moduleDirs().some((d) => existsSync(join(d, name, 'package.json')));
}

function lucideShim() {
  const names = new Set();
  for (const dir of ['app', 'components', 'lib']) {
    const abs = join(projectRoot, dir);
    if (!existsSync(abs)) continue;
    for (const f of walk(abs).filter((f) => /\.(tsx?|jsx?)$/.test(f))) {
      for (const m of readFileSync(f, 'utf8').matchAll(/import\s*\{([^}]*)\}\s*from\s*['"]lucide-react['"]/g)) {
        for (const n of m[1].split(',')) {
          const name = n.trim().split(/\s+as\s+/)[0].trim();
          if (name && name !== 'type') names.add(name);
        }
      }
    }
  }
  const lines = [
    "import { createElement } from 'react';",
    '// Placeholder icons generated by tests/harness/build.mjs because lucide-react is not installed.',
    'function make(name) {',
    "  const Icon = ({ size = 24, strokeWidth = 2, className, fill = 'none', style }) => createElement('svg', { width: size, height: size, viewBox: '0 0 24 24', fill, stroke: 'currentColor', strokeWidth, className, style, 'data-icon': name, 'aria-hidden': true }, createElement('rect', { x: 5, y: 5, width: 14, height: 14, rx: 4 }));",
    '  Icon.displayName = name;',
    '  return Icon;',
    '}',
    ...[...names].sort().map((n) => `export const ${n} = make('${n}');`),
  ];
  return lines.join('\n') + '\n';
}

export async function build({ quiet = false } = {}) {
  rmSync(buildDir, { recursive: true, force: true });
  mkdirSync(buildDir, { recursive: true });
  const plugins = [];
  const notes = [];

  if (!hasPackage('lucide-react')) {
    const shimPath = join(buildDir, 'lucide-shim.mjs');
    writeFileSync(shimPath, lucideShim());
    plugins.push({ name: 'lucide-shim', setup(b) { b.onResolve({ filter: /^lucide-react$/ }, () => ({ path: shimPath })); } });
    notes.push('lucide-react not installed: icons rendered as placeholders');
  }
  const cfShim = join(buildDir, 'cloudflare-workers-shim.mjs');
  writeFileSync(cfShim, '// Harness stand-in for the Workers runtime module.\nexport const env = new Proxy({}, { get: (_, k) => (typeof k === "string" ? process.env[k] : undefined) });\n');
  plugins.push({ name: 'cloudflare-workers-shim', setup(b) { b.onResolve({ filter: /^cloudflare:workers$/ }, () => ({ path: cfShim })); } });

  // Generated entries are plain .mjs on purpose: tsconfig includes **/*.ts(x), so a
  // generated .ts file in the build dir would leak into `tsc --noEmit`.
  const clientEntry = join(buildDir, 'client-entry.mjs');
  writeFileSync(clientEntry, [
    "import { createElement, StrictMode } from 'react';",
    "import { createRoot } from 'react-dom/client';",
    "import App from '@/app/page';",
    "const strict = new URLSearchParams(location.search).has('strict');",
    "const tree = createElement(App);",
    "createRoot(document.getElementById('root')).render(strict ? createElement(StrictMode, null, tree) : tree);",
  ].join('\n'));

  const routeFiles = walk(join(projectRoot, 'app', 'api')).filter((f) => /route\.ts$/.test(f));
  const routes = routeFiles.map((f) => {
    const rel = relative(join(projectRoot, 'app'), dirname(f)).replaceAll('\\', '/');
    return { file: f, pattern: '/' + rel };
  });
  const serverEntry = join(buildDir, 'server-entry.mjs');
  writeFileSync(serverEntry, routes.map((r, i) => `import * as r${i} from ${JSON.stringify(r.file)};`).join('\n') +
    `\nexport const routes = [${routes.map((r, i) => `{ pattern: ${JSON.stringify(r.pattern)}, mod: r${i} }`).join(', ')}];\n`);

  const common = { bundle: true, absWorkingDir: projectRoot, nodePaths: moduleDirs(), plugins, logLevel: quiet ? 'error' : 'warning', tsconfig: join(projectRoot, 'tsconfig.json'), jsx: 'automatic', sourcemap: 'inline' };
  await esbuild.build({ ...common, entryPoints: [clientEntry], outfile: join(buildDir, 'app.js'), platform: 'browser', format: 'esm', target: 'es2022', define: { 'process.env.NODE_ENV': '"development"' } });
  await esbuild.build({ ...common, entryPoints: [serverEntry], outfile: join(buildDir, 'routes.mjs'), platform: 'node', format: 'esm', target: 'node22' });
  writeFileSync(join(buildDir, 'build-info.json'), JSON.stringify({ builtAt: new Date().toISOString(), esbuild: esbuild.version, react: toolRequire('react/package.json').version, routes: routes.map((r) => r.pattern), notes }, null, 2));
  return { routes: routes.map((r) => r.pattern), notes };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const info = await build();
  console.log(JSON.stringify(info, null, 2));
}
